//! GLFW Win32 key identifiers and conversion of Winit's extended scan codes.
//! Numeric mapping follows GLFW's createKeyTables; no text/layout inference.
pub(crate) fn glfw_scan(native: u32) -> i32 {
    let scan=if native&0xff00==0xe000 {(native&0xff)|0x100} else {native};
    match scan {0x54=>0x137,0x146=>0x45,0x136=>0x36,_=>scan as i32}
}
pub(crate) fn glfw_key(scan: i32) -> i32 {
    match scan {
        0x0b=>48,0x02..=0x0a=>49+scan-2,
        0x1e=>65,0x30=>66,0x2e=>67,0x20=>68,0x12=>69,0x21=>70,
        0x22=>71,0x23=>72,0x17=>73,0x24=>74,0x25=>75,0x26=>76,
        0x32=>77,0x31=>78,0x18=>79,0x19=>80,0x10=>81,0x13=>82,
        0x1f=>83,0x14=>84,0x16=>85,0x2f=>86,0x11=>87,0x2d=>88,0x15=>89,0x2c=>90,
        0x28=>39,0x2b=>92,0x33=>44,0x0d=>61,0x29=>96,0x1a=>91,
        0x0c=>45,0x34=>46,0x1b=>93,0x27=>59,0x35=>47,0x56=>162,
        0x0e=>259,0x153=>261,0x14f=>269,0x1c=>257,0x01=>256,
        0x147=>268,0x152=>260,0x15d=>348,0x151=>267,0x149=>266,
        0x45=>284,0x39=>32,0x0f=>258,0x3a=>280,0x145=>282,0x46=>281,
        0x3b..=0x44=>290+scan-0x3b,0x57=>300,0x58=>301,
        0x64..=0x6e=>302+scan-0x64,0x76=>313,
        0x38=>342,0x1d=>341,0x2a=>340,0x15b=>343,0x137=>283,
        0x138=>346,0x11d=>345,0x36=>344,0x15c=>347,
        0x150=>264,0x14b=>263,0x14d=>262,0x148=>265,
        0x52=>320,0x4f=>321,0x50=>322,0x51=>323,0x4b=>324,
        0x4c=>325,0x4d=>326,0x47=>327,0x48=>328,0x49=>329,
        0x4e=>334,0x53=>330,0x135=>331,0x11c=>335,0x59=>336,0x37=>332,0x4a=>333,
        _=>-1,
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn source_scan_codes_keep_extended_keypad_navigation_and_special_cases() {
        for (native,scan,key) in [(0x1e,0x1e,65),(0xe01d,0x11d,345),
            (0xe01c,0x11c,335),(0xe053,0x153,261),(0x53,0x53,330),
            (0x54,0x137,283),(0xe046,0x45,284),(0xe036,0x36,344),
            (0x56,0x56,162),(0x76,0x76,313),(0x79,0x79,-1)] {
            assert_eq!(glfw_scan(native),scan); assert_eq!(glfw_key(scan),key);
        }
        for scan in 2..=10 {assert_eq!(glfw_key(scan),49+scan-2);}
        for scan in 0x3b..=0x44 {assert_eq!(glfw_key(scan),290+scan-0x3b);}
        for scan in 0x64..=0x6e {assert_eq!(glfw_key(scan),302+scan-0x64);}
    }
}
